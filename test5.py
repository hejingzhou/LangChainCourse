from dotenv import load_dotenv
from pydantic import BaseModel, Field
from langchain_openai import ChatOpenAI
import os

load_dotenv()

class AnalysisResult(BaseModel):
    key_point: str = Field(description="核心观点")
    confidence: float = Field(description="置信度，0-1")

class ArticleAnalysis(BaseModel):
    category: str = Field(description="文章类别...")
    sentiment: str = Field(description="...")
    summary: str = Field(description="...")
    result: AnalysisResult = Field(description="分析结果")


model = ChatOpenAI(
    model="deepseek-v4-pro",
    api_key=os.getenv("DEEPSEEK_API_KEY"),
    base_url="https://api.deepseek.com",
    temperature=0,
    extra_body={"thinking": {"type": "disabled"}},
)


# 将模型包装为结构化输出模型：
# 1. 第一个参数 ArticleAnalysis 指定了输出的 Pydantic 数据结构，
#    模型会按照该结构返回可解析的结果；
# 2. method="function_calling" 表示底层通过函数调用（function calling）
#    机制来约束并生成结构化的 JSON 输出。
#    method 还有别的选择，例如 "json_object"、"json_array" 等，根据需要选择
#    但是这里我们选择 "function_calling"，因为它更符合我们的需求。
structured_model = model.with_structured_output(
    ArticleAnalysis,
    method="function_calling",
)

